using System;
using System.Collections.Generic;
using System.Drawing;
using System.Linq;

namespace GamePartsApp
{
    // ====================================================================
    // Skillクラス：1つのスキルが持つデータをまとめる
    // ====================================================================
    // 「データ（Name, Description, Rarity）」と、
    // 「そのデータを使った表示処理（GetRarityStars, GetRarityColor）」を、
    // 同じクラスの中に持たせている。
    //
    // これにより、Form1.cs（画面側）は、
    // 「このスキルの星表示を教えて」「色を教えて」と
    // Skillに"お願いする"だけで済み、
    // 複雑な判定ロジックをいちいち知らなくてよくなっている。
    public class Skill
    {
        // ------------------------------------------------------------
        // プロパティ①：スキルの名前
        // ------------------------------------------------------------
        // { get; set; } の自動実装プロパティ。
        // getは「読み取り」、setは「書き込み」を、
        // それぞれ自動的に用意してくれる、一番シンプルなプロパティの書き方。
        public string Name { get; set; }

        // ------------------------------------------------------------
        // プロパティ②：スキルの説明文
        // ------------------------------------------------------------
        public string Description { get; set; }

        // ------------------------------------------------------------
        // プロパティ③：レア度（1=普通、2=レア、3=激レア）
        // ------------------------------------------------------------
        // 本来はenum（列挙型）にする方が、
        // タイプミスを防げてより安全だが、
        // 今回はシンプルさを優先してint型のままにしている。
        public int Rarity { get; set; }

        // ------------------------------------------------------------
        // コンストラクタ：生成と同時に、3つの情報を必須にする
        // ------------------------------------------------------------
        // これにより、new Skill() のように
        // 「何も指定せずに作る」ことができなくなり、
        // 「名前・説明・レア度、必ず全部揃えてから作る」ことが
        // クラス自身の力で保証される。
        public Skill(string name, string description, int rarity)
        {
            Name = name;
            Description = description;
            Rarity = rarity;
        }

        // ------------------------------------------------------------
        // GetRarityStars：レア度を、星の記号で表示する補助メソッド
        // ------------------------------------------------------------
        // 「このスキル自身が、自分の見た目（星の数）を知っている」
        // という設計。呼び出す側（Form1）は、
        // 「レア度が1だったら星1個」のような判定ロジックを
        // 自分で持たなくてよくなる。
        public string GetRarityStars()
        {
            // switch式：値を返すためだけの、短いswitch文の書き方。
            // _ は「それ以外すべて」を意味する記号（defaultに相当）。
            return Rarity switch
            {
                1 => "★",
                2 => "★★",
                3 => "★★★",
                _ => "?"  // 想定外の値が入っていた場合の、安全策
            };
        }

        // ------------------------------------------------------------
        // GetRarityColor：レア度に応じた「色」を返すメソッド
        // ------------------------------------------------------------
        // 色の意味づけ：
        //   Rarity=1（普通） → 緑
        //   Rarity=2（レア） → 青
        //   Rarity=3（激レア）→ 金（ゴールド）
        public Color GetRarityColor()
        {
            // Color.Green, Color.Blue のような「あらかじめ用意された色」に加え、
            // Color.FromArgb(...)で、自分でRGB値を指定した
            // 「金っぽい色」も作っている。
            return Rarity switch
            {
                1 => Color.Green,                 // 普通：緑
                2 => Color.Blue,                  // レア：青
                3 => Color.FromArgb(255, 215, 0),  // 激レア：金色（R,G,Bを指定）
                _ => Color.Black                  // 想定外の値のときは黒（安全策）
            };
        }
    }


    // ====================================================================
    // SkillSelector：スキル選択画面のロジックを担当するクラス
    // ====================================================================
    // このクラスの役割は「候補一覧から、3つを選ぶ」という
    // ”選択のロジック”だけに専念させている。
    // 「どう表示するか（色や星）」は、Skillクラス側に任せる、
    // という役割分担がポイント。
    public class SkillSelector
    {
        // ------------------------------------------------------------
        // 全スキルの「候補一覧」（プールと呼ばれる考え方）
        // ------------------------------------------------------------
        // private なので、SkillSelectorクラスの外からは
        // 直接アクセスできない（勝手に書き換えられない）。
        private List<Skill> allSkills;

        // ------------------------------------------------------------
        // 乱数生成器：ランダムな並び替えに使う
        // ------------------------------------------------------------
        private Random rand = new Random();

        // ------------------------------------------------------------
        // CurrentChoices：今、提示されている3つのスキル
        // ------------------------------------------------------------
        // get; private set; ＝ 読み取り専用プロパティ。
        // 外部（Form1）からは「読む」ことしかできず、
        // 「書き換える」ことはできない
        // （書き換えられるのは、SkillSelectorクラスの中だけ）。
        public List<Skill> CurrentChoices { get; private set; }

        //komennto

        // ------------------------------------------------------------
        // コンストラクタ：SkillSelectorが作られた瞬間に、
        // スキルの候補一覧をあらかじめ用意しておく
        // ------------------------------------------------------------
        public SkillSelector()
        {
            allSkills = new List<Skill>
            {
                // Rarity=1（普通）のスキル 3種類
                new Skill("素早い一撃", "攻撃速度が10%上がる", 1),
                new Skill("鉄壁の構え", "防御力が15%上がる", 1),
                new Skill("癒しの光", "回復量が20%上がる", 1),

                // Rarity=2（レア）のスキル 3種類
                new Skill("会心の一撃", "クリティカル率が10%上がる", 2),
                new Skill("疾風迅雷", "移動速度が25%上がる", 2),
                new Skill("生命の力", "最大HPが30上がる", 2),

                // Rarity=3（激レア）のスキル 2種類
                new Skill("覚醒", "全ステータスが20%上がる", 3),
                new Skill("不死鳥の加護", "戦闘不能を1回だけ防ぐ", 3),
            };

            // CurrentChoicesは、最初は空のListとして初期化しておく
            // （まだ何も選ばれていない状態）。
            CurrentChoices = new List<Skill>();
        }

        // ------------------------------------------------------------
        // RerollSkills：3つのスキルを、ランダムに選び直すメソッド
        // ------------------------------------------------------------
        // 戻り値なし（void）。
        // 「CurrentChoicesというプロパティの中身を、
        //   新しく書き換える」という”動作”だけを行う。
        public void RerollSkills()
        {
            // ------------------------------------------------------------
            // シャッフルのテクニック：ランダムな値を基準に並び替える
            // ------------------------------------------------------------
            // OrderBy(s => rand.Next())
            //
            // 読み方：「allSkillsの各要素(s)について、
            //           rand.Next()（ランダムな整数）を基準に並び替える」
            //
            // rand.Next()は呼ぶたびに違う値を返すため、
            // 結果として「毎回違う順番」に並び替わる＝シャッフルされる。
            var shuffled = allSkills.OrderBy(s => rand.Next()).ToList();

            // ------------------------------------------------------------
            // Take(3)：シャッフルされたListの、先頭3つだけを取り出す
            // ------------------------------------------------------------
            // これで「ランダムな3つ」が選ばれたことになる。
            CurrentChoices = shuffled.Take(3).ToList();
        }
    }
}


// ====================================================================
// 【このクラスの、他ファイルとの繋がり】
// ====================================================================
// Form1.cs：
//   SkillSelectorのインスタンスを1つ持ち、
//   RerollSkills() を呼んで3つのスキルを選び直し、
//   CurrentChoices の中身を、各Labelに反映している。
//
//   choices[0].GetRarityStars(), choices[0].GetRarityColor() のように、
//   Skillクラス自身の「表示に関するメソッド」を呼び出すことで、
//   Form1.cs側は複雑な判定ロジックを持たずに済んでいる。


// ====================================================================
// 【GachaItem/GachaManagerとの、構造の対応】
// ====================================================================
// Skill.cs                    GachaItem.cs / GachaManager.cs
// ─────────────────────────────────────────
// class Skill（データ）        class GachaItem（データ）
// class SkillSelector（ロジック） class GachaManager（ロジック）
//
// allSkills（候補一覧）        allItems（候補一覧）
// CurrentChoices（選ばれた3つ） （GachaManagerは1つだけ選ぶので、
//                                対応するプロパティはない）
// RerollSkills()               DrawGacha()
//
// 「候補一覧から選ぶ」という基本構造は同じだが、
// SkillSelectorは「3つを選ぶ（シャッフル+Take）」、
// GachaManagerは「1つを選ぶ（重み付き抽選）」という違いがある。


// ====================================================================
// 【なぜ表示ロジックを Skill クラス側に持たせたのか】
// ====================================================================
// もし色や星の判定を Form1.cs 側に直接書くと：
//
//   string stars;
//   if (choices[0].Rarity == 1) stars = "★";
//   else if (choices[0].Rarity == 2) stars = "★★";
//   ...
//
// このような長いif-elseを、Form1.csの中に
// 何度も書かなければならなくなる。
//
// GetRarityStars(), GetRarityColor() として
// Skillクラス自身に持たせることで：
//
//   skill1RarityLabel.Text = choices[0].GetRarityStars();
//   skill1Label.ForeColor = choices[0].GetRarityColor();
//
// と、それぞれ1行で済むようになる。
//
// これは、以前一緒に整理した
// 「クラスは、自分に関するデータと処理を、
//   自分自身の中にまとめておくべき」という
// オブジェクト指向の基本的な考え方の実践。