using System;
using System.Collections.Generic;

namespace GamePartsApp
{
    // ====================================================================
    // GachaManager：ガチャの抽選ロジックを担当するクラス
    // ====================================================================
    /// <summary>
    ///  ガチャのアイテムプールと重み付き抽選を管理します。外部からは
    ///  GetAllItems や DrawGacha を通して利用します。
    /// </summary>
    // このクラスの役割は「ガチャに関する処理」に専念すること。
    // 「どんなアイテムがあるか」「どうやって1つを選ぶか」を、
    // このクラス1つに集約している。
    //
    // Form1.cs（画面側）は、このクラスの機能を「呼び出すだけ」で、
    // 抽選の詳しいロジックを知らなくてもガチャを使えるようになっている。
    // これが、以前学んだ「データ・ロジックをクラスにまとめる」考え方の実践。
    public class GachaManager
    {
        // ------------------------------------------------------------
        // フィールド①：全アイテムの一覧（プール）
        // ------------------------------------------------------------
        // private なので、GachaManagerクラスの外からは
        // 直接この変数を触ることができない。
        // 触りたい場合は、下の GetAllItems() メソッド経由でのみ可能
        // （これも「勝手に書き換えられない」ようにする安全設計）。
        private List<GachaItem> allItems;

        // ------------------------------------------------------------
        // フィールド②：乱数生成器
        // ------------------------------------------------------------
        // = new Random() と書くことで、
        // フィールドの宣言と同時に、インスタンスを1つ作っている。
        // このクラスの中で、乱数が必要な場面（DrawGacha）で使い回す。
        private Random rand = new Random();

        // ------------------------------------------------------------
        // GetAllItems：allItemsを、外部（Form1.cs）に見せるためのメソッド
        // ------------------------------------------------------------
        // allItemsはprivateなので、そのままではForm1.csから見えない。
        // このメソッドを通すことで、「読み取りだけ」を許可している。
        //
        // これは、スロット機能で「ガチャと同じアイテムリストを
        // 再利用したい」ときに使われている
        // （Form1.cs側で slotItems = gachaManager.GetAllItems(); と書いていた）。
        public List<GachaItem> GetAllItems()
        {
            return allItems;
        }

        // ------------------------------------------------------------
        // コンストラクタ：GachaManagerが作られた瞬間に実行される
        // ------------------------------------------------------------
        // ここで、ガチャに登場する全アイテムを、あらかじめ用意しておく。
        public GachaManager()
        {
            // ------------------------------------------------------------
            // 通常アイテム6種類を、一気にListとして初期化する
            // ------------------------------------------------------------
            // オブジェクト初期化子（{ ... }）の中に、
            // 複数の new GachaItem(...) を、カンマ区切りで並べている。
            // これにより、1回のnewで6個ぶんのアイテムを一気に作れる。
            //
            // GachaItemのコンストラクタは (名前, レア度, 画像パス) の順。
            allItems = new List<GachaItem>
            {
                // ------------------------------------------------------------
                // レア度1（銅）：出現率が高い、基本的なアイテム
                // ------------------------------------------------------------
                new GachaItem("コウテイペンギンのヒナ", 1, @"images\animal_koutei_penguin_hina.png"),
                new GachaItem("ジェンツーペンギン", 1, @"images\penguin03_gentoo.png"),

                // ------------------------------------------------------------
                // レア度3（金）：アデリーペンギンは、
                // 当初レア度1だったが、後からレア度3に変更された
                // （「アデリーだけ金に変えた」という要望を反映した部分）。
                // ------------------------------------------------------------
                new GachaItem("アデリーペンギン", 3, @"images\penguin04_adelie.png"),

                // ------------------------------------------------------------
                // レア度2（銀）：中間くらいの珍しさ
                // ------------------------------------------------------------
                new GachaItem("キングペンギンのヒナ", 2, @"images\penguin_king_hina.png"),
                new GachaItem("スマホペンギン", 2, @"images\animal_chara_smartphone_penguin.png"),

                // ------------------------------------------------------------
                // レア度4（虹）：一番珍しい、最高レアリティ
                // ------------------------------------------------------------
                new GachaItem("宇宙ペンギン", 4, @"images\space_uchu_penguin.png"),
            };

            // ------------------------------------------------------------
            // 歩くペンギン（歩行アニメ付き）を、別途作って追加する
            // ------------------------------------------------------------
            // GachaItemのコンストラクタは (名前, レア度, 画像パス) の3つだが、
            // ここでは通常の3引数だけで、まず1つのインスタンスを作っている。
            // ImagePathには「1枚目の画像」を、通常表示用として渡している。
            GachaItem walkingPenguin = new GachaItem("歩くペンギン", 3, @"images\penguin_walk_frame1.png");

            // ------------------------------------------------------------
            // WalkFramesプロパティに、後から3枚のパスを追加していく
            // ------------------------------------------------------------
            // GachaItemクラスの中で、
            //   WalkFrames = new List<string>();
            // という形で「空のList」として初期化されているため、
            // ここで .Add() を3回呼んで、1つずつ追加できる。
            //
            // これにより walkingPenguin.WalkFrames の中身は：
            //   [0] = penguin_walk_frame1.png
            //   [1] = penguin_walk_frame2.png
            //   [2] = penguin_walk_frame3.png
            // という、3枚のリストになる。
            walkingPenguin.WalkFrames.Add(@"images\penguin_walk_frame1.png");
            walkingPenguin.WalkFrames.Add(@"images\penguin_walk_frame2.png");
            walkingPenguin.WalkFrames.Add(@"images\penguin_walk_frame3.png");

            // ------------------------------------------------------------
            // 作った「歩くペンギン」を、全アイテムのリストに追加する
            // ------------------------------------------------------------
            // これで、allItems の中身は「通常6種類＋歩くペンギン」の
            // 合計7種類になる。
            allItems.Add(walkingPenguin);
        }

        // ====================================================================
        // DrawGacha：ガチャを1回引くメソッド（重み付き抽選）
        // ====================================================================
        // 戻り値の型が GachaItem なので、
        // 「抽選の結果、選ばれたアイテム」を1つ返すメソッド。
        public GachaItem DrawGacha()
        {
            // ------------------------------------------------------------
            // Step 1：全アイテムの「重み」を計算し、合計値も出す
            // ------------------------------------------------------------
            // totalWeight：全アイテムの重みを、全部足し合わせた合計値
            int totalWeight = 0;

            // weights：各アイテムに対応する「重み」を保存しておく辞書
            // Dictionary<GachaItem, int> なので、
            //   キー   ＝ どのアイテムか
            //   値     ＝ そのアイテムの重み（数値）
            // というペアで管理している。
            var weights = new Dictionary<GachaItem, int>();

            // ------------------------------------------------------------
            // allItemsを、1つずつforeachで処理する
            // ------------------------------------------------------------
            foreach (var item in allItems)
            {
                // ------------------------------------------------------------
                // レア度から、「重み」を決める（switch式）
                // ------------------------------------------------------------ 
                // 重みが大きいほど「出やすい」、
                // 重みが小さいほど「出にくい」という意味になる。
                //
                // 銅（1）は重み50、虹（4）は重み5、
                // というように、レア度が上がるほど重みを小さくすることで、
                // 「レアなアイテムほど当たりにくい」ガチャらしさを表現している。
                int weight = item.Rarity switch
                {
                    1 => 50,  // 銅：出やすい
                    2 => 30,  // 銀：普通
                    3 => 15,  // 金：レア
                    4 => 5,   // 虹：激レア
                    _ => 1    // 想定外のレア度が入っていた場合の、安全策
                };

                // ------------------------------------------------------------
                // このアイテムの重みを、辞書に記録しておく
                // ------------------------------------------------------------
                weights[item] = weight;

                // ------------------------------------------------------------
                // 全体の合計値にも、この重みを足しておく
                // ------------------------------------------------------------
                totalWeight += weight;
            }

            // この時点で：
            //   totalWeight = 50+50+15+30+30+5+15（歩くペンギン分） = 195
            //   （実際の値は、登録されているアイテムの構成による）

            // ------------------------------------------------------------
            // Step 2：0〜totalWeight未満の、ランダムな整数を1つ選ぶ
            // ------------------------------------------------------------
            // これが「くじ引きの、当たり番号」に相当する。
            int randomValue = rand.Next(0, totalWeight);

            // ------------------------------------------------------------
            // Step 3：「累計の重み」を使って、randomValueがどのアイテムの
            // 区間に入っているかを判定する
            // ------------------------------------------------------------
            // cumulative：ここまでの重みの「累計（積み上げ）」を覚えておく変数
            int cumulative = 0;

            foreach (var item in allItems)
            {
                // このアイテムの重みを、累計に足す
                cumulative += weights[item];

                // ------------------------------------------------------------
                // randomValueが、今の累計より小さければ、
                // 「このアイテムの区間に入った」ということ
                // ------------------------------------------------------------
                // イメージ（重みが 銅50, 銀30, 虹5 の3種類だとする）：
                //
                //   0────────────────────────85────90
                //   [────────銅(重み50)────][──銀(30)──][虹(5)]
                //
                //   1周目：cumulative = 50
                //     randomValueが0〜49なら、ここで条件成立 → 銅を返す
                //
                //   2周目：cumulative = 80
                //     randomValueが50〜79なら、ここで条件成立 → 銀を返す
                //
                //   3周目：cumulative = 85
                //     randomValueが80〜84なら、ここで条件成立 → 虹を返す
                //
                // 「重みが大きいアイテム」ほど、
                // この区間の「幅」が広くなるので、
                // 結果的に「当たりやすく」なる。
                if (randomValue < cumulative)
                {
                    // 条件を満たした瞬間、そのアイテムを返して、
                    // メソッドの処理はここで終了する（returnの性質）。
                    return item;
                }
            }

            // ------------------------------------------------------------
            // 万が一、どのアイテムにも当てはまらなかった場合の保険
            // ------------------------------------------------------------
            // 理論上はここに来ないはずだが（計算上、必ずどこかで
            // randomValue < cumulative が成立するため）、
            // コンパイラに「必ず何かを返す」ことを保証するために、
            // 念のため書いておく安全策。
            return allItems[0];
        }
    }
}