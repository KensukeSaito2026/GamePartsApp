// GachaManager.cs：
//   このGachaItemを、複数個まとめて List<GachaItem> として管理している。
//   DrawGacha() メソッドが、重み付き抽選で1つのGachaItemを選んで返す。
//
// Form1.cs：
//   ガチャの結果として受け取ったGachaItemの、
//   GetRarityLabel(), CreateOverlaidImage(), HasWalkAnimation() を
//   呼び出して、画面に表示している。
//
//   スロット機能でも、GachaManager.GetAllItems() 経由で、
//   同じ GachaItem のリストを再利用している。


// ====================================================================
// 【この設計のポイント：なぜ全部1つのクラスにまとめたか】
// ====================================================================
// もし「レア度から色を決める」処理を、Form1.cs側に直接書くと：
//
//   Color color;
//   if (item.Rarity == 1) color = Color.FromArgb(80, 139, 69, 19);
//   else if (item.Rarity == 2) color = Color.FromArgb(80, 192, 192, 192);
//   ... （と、長いif-elseが必要になる）
//
// GetOverlayColor() として GachaItem自身に持たせることで、
//
//   Color color = item.GetOverlayColor();
//
// と、たった1行で済むようになる。
//
// これは「クラスは、自分に関するデータと処理を、
// 自分自身の中にまとめておくべき」という、
// オブジェクト指向の基本的な考え方の実践。