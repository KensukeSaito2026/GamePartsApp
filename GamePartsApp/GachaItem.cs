using System;
using System.Drawing;
using System.Collections.Generic;

namespace GamePartsApp
{
    // ====================================================================
    // GachaItemクラス：1つのガチャアイテムのデータをまとめる
    // ====================================================================
    // このクラスは「1つのアイテムに関する、あらゆる情報と機能」を
    // 1か所にまとめている。
    //
    // 「データ（Name, Rarity, ImagePath, WalkFrames）」だけでなく、
    // 「そのデータを使って何をするか（GetRarityLabel, GetOverlayColor,
    //   CreateOverlaidImage）」も、同じクラスの中に持たせているのが特徴。
    //
    // これにより、Form1.cs（画面側）は、
    // 「このアイテムのレア度ラベルを教えて」「色マスク付き画像を作って」
    // と、GachaItemに"お願いする"だけで済み、
    // 複雑な計算の中身を、いちいち知らなくてもよくなっている。
    public class GachaItem
    {
        // ------------------------------------------------------------
        // プロパティ①：アイテムの名前
        // ------------------------------------------------------------
        // { get; set; } の自動実装プロパティ。
        // getは「読み取り」、setは「書き込み」を、それぞれ自動的に
        // 用意してくれる、一番シンプルなプロパティの書き方。
        public string Name { get; set; }

        // ------------------------------------------------------------
        // プロパティ②：レア度
        // ------------------------------------------------------------
        // 1=普通(銅)、2=レア(銀)、3=激レア(金)、4=虹（最上位）という
        // ルールを、コメントとして書いておくことで、
        // 後から読む人（未来の自分も含む）が迷わないようにしている。
        //
        // 本来はenum（列挙型）で書く方がより安全だが、
        // 今回はシンプルさを優先してint型のまま扱っている。
        public int Rarity { get; set; }

        // ------------------------------------------------------------
        // プロパティ③：画像ファイルへのパス
        // ------------------------------------------------------------
        // このアイテムの「通常時（静止画）」の見た目を表す、
        // 画像ファイルの場所を文字列で持っている。
        public string ImagePath { get; set; }

        // ------------------------------------------------------------
        // プロパティ④：歩行アニメーションのフレーム一覧
        // ------------------------------------------------------------
        // 通常のアイテムは、このリストが「空」のまま。
        // 「歩くペンギン」のような、特別な演出を持つアイテムだけ、
        // ここに複数枚の画像パスが入る。
        public List<string> WalkFrames { get; set; }

        // ------------------------------------------------------------
        // コンストラクタ：GachaItemが作られた瞬間の初期化
        // ------------------------------------------------------------
        // walkFrames = null という書き方は、
        // 「省略可能な引数」（以前学んだ内容）。
        //
        // 通常のアイテムを作るときは：
        //   new GachaItem("名前", 1, "パス")
        //   → walkFramesを省略できる（自動的にnullが渡される）
        //
        // 歩くペンギンのように、後から追加したい場合は：
        //   new GachaItem("名前", 3, "パス")
        //   その後、.WalkFrames.Add(...) を呼んで、
        //   1つずつ追加していく、という使い方をしている。
        public GachaItem(string name, int rarity, string imagePath, List<string> walkFrames = null)
        {
            Name = name;
            Rarity = rarity;
            ImagePath = imagePath;

            // ------------------------------------------------------------
            // ?? （null合体演算子）：以前学んだ、便利な記法
            // ------------------------------------------------------------
            // 「walkFramesがnullでなければ、そのまま使う。
            //   nullだったら、代わりに new List<string>() を使う」
            // という意味。
            //
            // これにより、WalkFrames が「絶対にnullにならない」ことが
            // 保証される。
            //
            // 【今日実際に起きたバグとの関連】
            // このnull対策のおかげで、WalkFramesがnullで落ちる、
            // というエラーは今回起きなかった。
            // 実際に起きたのは「WalkFrames.Countが0のアイテムに対して、
            // 別の場所（Form1.cs）でTimerが動き続けてしまった」という、
            // 少し違う種類のバグだった
            // （詳細は Form1.cs の walkAnimationTimer_Tick の解説を参照）。
            WalkFrames = walkFrames ?? new List<string>();
        }

        // ------------------------------------------------------------
        // HasWalkAnimation：歩行アニメを持っているかどうかを判定する
        // ------------------------------------------------------------
        // このメソッドが true を返すのは、
        // 「WalkFramesがnullでなく、かつ1枚以上の画像が入っている」
        // ときだけ。
        //
        // 通常のアイテム（歩くペンギン以外）は、
        // コンストラクタで WalkFrames = new List<string>() と
        // 初期化されるため、Count は必ず 0 になり、
        // このメソッドは false を返す。
        public bool HasWalkAnimation()
        {
            return WalkFrames != null && WalkFrames.Count > 0;
        }

        // ------------------------------------------------------------
        // GetRarityLabel：レア度を、日本語のラベルとして返す
        // ------------------------------------------------------------
        // switch式（以前学んだ、switch文の短縮バージョン）を使い、
        // Rarityの値に応じて、対応する日本語の文字列を返している。
        //
        // _ は「それ以外すべて」を意味する記号（defaultに相当）。
        // 想定外の数値が入っていた場合の、安全策になっている。
        public string GetRarityLabel()
        {
            return Rarity switch
            {
                1 => "銅",
                2 => "銀",
                3 => "金",
                4 => "虹",
                _ => "?"
            };
        }

        // ------------------------------------------------------------
        // GetOverlayColor：レア度に応じた「マスクの色」を返す
        // ------------------------------------------------------------
        // Color.FromArgb(透明度, R, G, B) という書き方で、
        // 「半透明の色」を作っている。
        //
        // 第1引数の「80」は透明度（0〜255）。
        // 0=完全に透明、255=完全に不透明。
        // 80くらいだと、下の画像が透けて見える、
        // うっすらとした色付けになる。
        public Color GetOverlayColor()
        {
            return Rarity switch
            {
                1 => Color.FromArgb(80, 139, 69, 19),    // 銅：茶色っぽい半透明
                2 => Color.FromArgb(80, 192, 192, 192),  // 銀：グレーの半透明
                3 => Color.FromArgb(80, 255, 215, 0),    // 金：金色の半透明
                4 => Color.FromArgb(80, 255, 0, 255),    // 虹：仮でマゼンタ
                _ => Color.FromArgb(0, 0, 0, 0)          // 透明（0,0,0,0＝完全に見えない色）
            };
        }

        // ------------------------------------------------------------
        // CreateOverlaidImage：画像に、レア度の色マスクを重ねた
        // 新しい画像（Bitmap）を作って返すメソッド
        // ------------------------------------------------------------
        // 戻り値の型が Bitmap（編集可能な画像データ）。
        // 「元の画像＋色マスク」を合成した、新しい1枚の画像を作って返す。
        public Bitmap CreateOverlaidImage()
        {
            // ------------------------------------------------------------
            // using：使い終わったら自動的に片付けてくれる仕組み
            // ------------------------------------------------------------
            // Image, Graphics のような「画像・描画に関するリソース」は、
            // 使い終わったら明示的に解放しないと、
            // メモリを無駄に使い続けてしまう性質がある。
            // usingで囲むことで、そのブロックを抜けた瞬間に、
            // 自動的に後片付けが行われる。
            //
            // Image.FromFile(ImagePath) で、
            // ImagePathに保存されている画像ファイルを読み込んでいる。
            using (Image original = Image.FromFile(ImagePath))
            {
                // ------------------------------------------------------------
                // 元の画像と同じサイズの、新しいBitmapを用意する
                // ------------------------------------------------------------
                // Bitmap：画像データを、実際に「編集できる形」で持つクラス。
                // ここに、元の画像＋色マスクを、これから描き込んでいく。
                Bitmap result = new Bitmap(original.Width, original.Height);

                // ------------------------------------------------------------
                // Graphics：この新しいBitmapに「描画するための道具」
                // ------------------------------------------------------------
                // 以前のDrawApp（お絵かきアプリ）で使った
                // e.Graphics と、全く同じ種類のオブジェクト。
                // 「筆」のようなイメージで、resultという”キャンバス”の上に
                // 絵を描いていく。
                using (Graphics g = Graphics.FromImage(result))
                {
                    // ------------------------------------------------------------
                    // ① まず、元の画像を、そのまま描く
                    // ------------------------------------------------------------
                    // DrawImage(画像, x座標, y座標, 幅, 高さ) で、
                    // (0, 0)の位置から、元のサイズのまま描画している。
                    g.DrawImage(original, 0, 0, original.Width, original.Height);

                    // ------------------------------------------------------------
                    // ② その上から、半透明の色を「重ねて塗る」
                    // ------------------------------------------------------------
                    // SolidBrush：塗りつぶし用の「絵の具」を表すクラス。
                    // GetOverlayColor() で取得した「半透明の色」を使うことで、
                    // 「完全に塗りつぶす」のではなく、
                    // 「うっすら色を乗せる」効果になる。
                    //
                    // FillRectangle(絵の具, x, y, 幅, 高さ) で、
                    // 画像全体を覆うように、四角形を塗りつぶしている。
                    using (SolidBrush overlayBrush = new SolidBrush(GetOverlayColor()))
                    {
                        g.FillRectangle(overlayBrush, 0, 0, original.Width, original.Height);
                    }
                }

                // ------------------------------------------------------------
                // 完成した画像（result）を、呼び出し元に返す
                // ------------------------------------------------------------
                return result;
            }
        }
    }
}


