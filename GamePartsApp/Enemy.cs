using System;

namespace GamePartsApp
{
    // ====================================================================
    // Enemyクラス：すべての敵の「共通の親」となる基底クラス
    // ====================================================================
    // WeakEnemy（雑魚）、Boss（ボス）は、両方ともこのEnemyを継承する。
    //
    // 「WeakEnemy is a Enemy」「Boss is a Enemy」
    // （雑魚もボスも、Enemyの一種）という、
    // 今日整理した「継承（is-aの関係）」の実践。
    //
    // 共通する部分（位置、HP、当たり判定など）をここにまとめておくことで、
    // WeakEnemy.cs や Boss.cs では、
    // "その敵だけの特別な行動"だけを書けばよくなる。
    public class Enemy
    {
        // ------------------------------------------------------------
        // 位置に関するプロパティ
        // ------------------------------------------------------------
        public float X { get; set; }
        public float Y { get; set; }

        // ------------------------------------------------------------
        // ステータス
        // ------------------------------------------------------------
        // { get; protected set; } ← 今回初登場のアクセス修飾子
        //
        // protected は、「このクラス自身」だけでなく、
        // 「このクラスを継承した子クラス（WeakEnemy, Boss）」からも
        // 書き込みを許可する、という意味。
        //
        // private だと、Enemyクラスの中からしか書き込めないが、
        // protected なら、子クラスの中からも
        // HP = ... のように直接操作できる。
        public int HP { get; protected set; }
        public int MaxHP { get; protected set; }
        public int AttackPower { get; protected set; }
        public float Radius { get; set; } = 20f;  // 当たり判定の半径

        // ------------------------------------------------------------
        // 名前（画面表示やデバッグ用）
        // ------------------------------------------------------------
        public string Name { get; protected set; } = "敵";

        // ------------------------------------------------------------
        // コンストラクタ
        // ------------------------------------------------------------
        // 子クラス（WeakEnemy, Boss）から、
        // base(...) という書き方で、このコンストラクタを呼び出す想定。
        public Enemy(string name, float startX, float startY, int maxHp, int attackPower)
        {
            Name = name;
            X = startX;
            Y = startY;
            MaxHP = maxHp;
            HP = maxHp;
            AttackPower = attackPower;
        }

        // ------------------------------------------------------------
        // ダメージを受ける
        // ------------------------------------------------------------
        // これは今日、Player.csでも全く同じ形で書いた処理。
        // Math.Max で、HPが0未満にならないようにしている。
        //
        // virtual が付いているのは、
        // 「子クラス側で、この処理を"上書き"してもいいですよ」
        // という意味（今回は使わないが、
        // 将来「ボスだけ特別な被弾処理をしたい」ときに応用できる）。
        public virtual void TakeDamage(int damage)
        {
            HP = Math.Max(HP - damage, 0);
        }

        // ------------------------------------------------------------
        // 生存判定（式形式プロパティ、以前のPlayerでも使った書き方）
        // ------------------------------------------------------------
        public bool IsAlive => HP > 0;

        // ------------------------------------------------------------
        // 2点間の距離を計算する（当たり判定などで、共通して使う）
        // ------------------------------------------------------------
        // protected：Enemyクラスと、その子クラスからだけ使える
        // static ではない理由：
        //   このメソッド自体はデータを使わないが、
        //   「Enemy系のクラスだけで使う、共通の道具」として、
        //   ここにまとめておく方が管理しやすいため。
        protected float GetDistance(float x1, float y1, float x2, float y2)
        {
            float dx = x1 - x2;
            float dy = y1 - y2;
            return (float)Math.Sqrt(dx * dx + dy * dy);
        }

        // ------------------------------------------------------------
        // 毎フレーム呼ばれる、状態更新処理
        // ------------------------------------------------------------
        // virtual：子クラス（WeakEnemy, Boss）が、
        // それぞれ自分専用の更新処理を持てるようにする。
        //
        // 子クラス側では、
        //   public override void UpdateFrame(...)
        // という形で、この中身を"上書き"して使う。
        public virtual void UpdateFrame(float playerX, float playerY)
        {
            // 基底クラスでは、特に何もしない（子クラスで実装する）
        }
    }
}